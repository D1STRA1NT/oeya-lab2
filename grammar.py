"""Словарь языка запросов к библиотеке.

Определяет, какие слова допустимы и к какой части запроса они относятся.
Модуль разбора опирается на этот словарь и не принимает слова вне списков.
"""
# запрос   = глагол объект

# глагол   = "найди" | "покажи" | "выведи"
VERBS = {"найди", "покажи", "выведи"}

# объект   = [все] тип фильтр*
# [все]    — не обязательно
QUANTIFIER = "все"
# тип      = книги | статьи | журналы
TYPES = {"книги", "статьи", "журналы"}

# фильтр   = год | авторы | тема | издание
# фильтр*  — ни одного, один или несколько подряд

# год      = ЧИСЛО "года"
WORD_GODA = "года"

# авторы   = имя (и имя)*
# имя      = толстого | достоевского
NAMES = {"толстого", "достоевского"}
WORD_AND = "и"

# тема     = "по" ТЕМА
# ТЕМА     = программированию | лингвистике
WORD_PO = "по"
TOPICS = {"программированию", "лингвистике"}

# издание  = "изданные" "после" ЧИСЛО
WORD_IZDANNYE = "изданные"
WORD_POSLE = "после"


def word_kind(word):
    """Определяет, к какой части запроса относится слово.

    Args:
        word: Слово в нижнем регистре.

    Returns:
        Роль слова в запросе. Пустое значение, если такого слова в языке нет.
    """
    # число не хранится в списках и проверяется отдельно
    if word in VERBS:
        return "VERB"
    if word == QUANTIFIER:
        return "ALL"
    if word in TYPES:
        return "TYPE"
    if word in NAMES:
        return "NAME"
    if word in TOPICS:
        return "TOPIC"
    if word == WORD_PO:
        return "PO"
    if word == WORD_POSLE:
        return "POSLE"
    if word == WORD_GODA:
        return "GODA"
    if word == WORD_IZDANNYE:
        return "IZDANNYE"
    if word == WORD_AND:
        return "AND"
    if word.isdigit():
        return "NUMBER"
    return None
